package com.parkspot.service;

import com.parkspot.dto.DailyReportResponse;
import com.parkspot.dto.ParkingEntryRequest;
import com.parkspot.dto.ParkingRecordResponse;
import com.parkspot.entity.Flat;
import com.parkspot.entity.ParkingRecord;
import com.parkspot.entity.ParkingSlot;
import com.parkspot.entity.ParkingStatus;
import com.parkspot.entity.SlotStatus;
import com.parkspot.entity.VisitorVehicle;
import com.parkspot.exception.InvalidParkingOperationException;
import com.parkspot.exception.ResourceNotFoundException;
import com.parkspot.exception.SlotAlreadyOccupiedException;
import com.parkspot.exception.VehicleAlreadyParkedException;
import com.parkspot.repository.ParkingRecordRepository;
import com.parkspot.repository.ParkingSlotRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.LocalTime;
import java.time.temporal.ChronoUnit;
import java.util.List;

/**
 * All parking business rules live in this class (not in the controller, not only in the database).
 */
@Service
@Transactional(readOnly = true)
public class ParkingService {

    // used when no date filter is given in the history search
    private static final LocalDateTime SEARCH_START = LocalDateTime.of(2000, 1, 1, 0, 0);
    private static final LocalDateTime SEARCH_END = LocalDateTime.of(2999, 12, 31, 23, 59);

    private final ParkingRecordRepository recordRepository;
    private final ParkingSlotRepository slotRepository;
    private final VehicleService vehicleService;
    private final FlatService flatService;

    public ParkingService(ParkingRecordRepository recordRepository, ParkingSlotRepository slotRepository,
                          VehicleService vehicleService, FlatService flatService) {
        this.recordRepository = recordRepository;
        this.slotRepository = slotRepository;
        this.vehicleService = vehicleService;
        this.flatService = flatService;
    }

    // ------------------------------------------------------------------ ENTRY

    @Transactional
    public ParkingRecordResponse registerEntry(ParkingEntryRequest request) {
        String slotNumber = request.slotNumber().trim().toUpperCase();

        // Rule 5: slot must exist (row is locked until this transaction ends)
        ParkingSlot slot = slotRepository.findBySlotNumberForUpdate(slotNumber)
                .orElseThrow(() -> new ResourceNotFoundException("Parking slot " + slotNumber + " does not exist."));
        Flat flat = flatService.findEntityByNumber(request.flatNumber());
        VisitorVehicle vehicle = vehicleService.findOrRegister(request);

        // Rule 3 and Rule 1: both checks happen BEFORE anything is saved
        ensureVehicleNotParked(vehicle);
        ensureSlotAvailable(slot);

        ParkingRecord record = new ParkingRecord();
        record.setVisitorVehicle(vehicle);
        record.setFlat(flat);
        record.setParkingSlot(slot);
        record.setPurpose(request.purpose() == null ? null : request.purpose().trim());
        record.setEntryTime(currentTime());          // entry time is generated by the server
        record.setStatus(ParkingStatus.ACTIVE);

        slot.setStatus(SlotStatus.OCCUPIED);
        slotRepository.save(slot);
        return ParkingRecordResponse.from(recordRepository.save(record));
    }

    private void ensureVehicleNotParked(VisitorVehicle vehicle) {
        if (recordRepository.existsByVisitorVehicleAndStatus(vehicle, ParkingStatus.ACTIVE)) {
            throw new VehicleAlreadyParkedException("Vehicle " + vehicle.getVehicleNumber() + " is already parked.");
        }
    }

    private void ensureSlotAvailable(ParkingSlot slot) {
        if (slot.getStatus() == SlotStatus.OCCUPIED) {
            throw new SlotAlreadyOccupiedException("Parking slot " + slot.getSlotNumber() + " is already occupied.");
        }
    }

    // ------------------------------------------------------------------- EXIT

    @Transactional
    public ParkingRecordResponse recordExit(Long recordId) {
        ParkingRecord record = recordRepository.findById(recordId)
                .orElseThrow(() -> new ResourceNotFoundException("Parking record with id " + recordId + " not found."));

        // Rule 4: only an ACTIVE record can be exited
        if (record.getStatus() == ParkingStatus.COMPLETED) {
            throw new InvalidParkingOperationException("Parking record has already been completed.");
        }
        // Rule 2: an exit time cannot exist without an entry time, and must not be before it
        LocalDateTime exitTime = currentTime();
        validateTimes(record.getEntryTime(), exitTime);

        record.setExitTime(exitTime);
        record.setStatus(ParkingStatus.COMPLETED);

        ParkingSlot slot = record.getParkingSlot();
        slot.setStatus(SlotStatus.AVAILABLE);          // slot can be used again
        slotRepository.save(slot);
        return ParkingRecordResponse.from(recordRepository.save(record));
    }

    private void validateTimes(LocalDateTime entryTime, LocalDateTime exitTime) {
        if (entryTime == null) {
            throw new InvalidParkingOperationException("Exit cannot be recorded because there is no entry time.");
        }
        if (exitTime.isBefore(entryTime)) {
            throw new InvalidParkingOperationException("Exit time cannot be before entry time.");
        }
    }

    // ---------------------------------------------------------------- QUERIES

    public List<ParkingRecordResponse> getActiveRecords() {
        return recordRepository.findByStatusOrderByEntryTimeDesc(ParkingStatus.ACTIVE).stream()
                .map(ParkingRecordResponse::from).toList();
    }

    /** Completed records, optionally filtered by vehicle number, flat number and entry date. */
    public List<ParkingRecordResponse> getHistory(String vehicleNumber, String flatNumber, LocalDate date) {
        String vehicleFilter = vehicleNumber == null ? "" : VehicleService.normalizeNumber(vehicleNumber);
        String flatFilter = flatNumber == null ? "" : flatNumber.trim().toUpperCase();
        LocalDateTime from = date == null ? SEARCH_START : date.atStartOfDay();
        LocalDateTime to = date == null ? SEARCH_END : date.atTime(LocalTime.MAX);

        return recordRepository.searchByStatus(ParkingStatus.COMPLETED, vehicleFilter, flatFilter, from, to)
                .stream().map(ParkingRecordResponse::from).toList();
    }

    /** Daily visitor log: every visit whose entry time falls on the selected date. */
    public DailyReportResponse getDailyReport(LocalDate date) {
        LocalDate day = date == null ? LocalDate.now() : date;
        List<ParkingRecordResponse> records = recordRepository
                .findByEntryTimeBetweenOrderByEntryTimeAsc(day.atStartOfDay(), day.atTime(LocalTime.MAX))
                .stream().map(ParkingRecordResponse::from).toList();

        long completed = records.stream().filter(r -> r.status() == ParkingStatus.COMPLETED).count();
        // "Currently Inside" is a live count, so it must include vehicles that entered
        // on an earlier day and have not exited yet.
        long inside = recordRepository.countByStatus(ParkingStatus.ACTIVE);
        return new DailyReportResponse(day, records.size(), completed, inside, records);
    }

    public List<ParkingRecordResponse> getRecentRecords() {
        return recordRepository.findTop5ByOrderByEntryTimeDesc().stream()
                .map(ParkingRecordResponse::from).toList();
    }

    private LocalDateTime currentTime() {
        return LocalDateTime.now().truncatedTo(ChronoUnit.SECONDS);
    }
}
